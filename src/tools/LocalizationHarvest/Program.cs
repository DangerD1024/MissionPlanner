// Harvests Mission Planner's translations for the cross-platform app.
//
//   dotnet run --project src/tools/LocalizationHarvest [repo-root]
//
// 1. Pairs every English .resx entry (ExtLibs/Strings/Strings.resx and the WinForms screens' Foo.resx)
//    with the same key in its culture siblings (Foo.ru-KZ.resx...) and writes, per language,
//    src/MissionPlanner.App/Localization/<culture>.json. The "overrides" section of an existing file is kept.
// 2. Finds the app's UI strings ({l:Tr} in XAML, L.Tr/L.Format/dialog/menu literals in C#), prints how
//    many each language translates and writes the gaps to src/MissionPlanner.App/Localization/untranslated.txt.

using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using MissionPlanner.App.Core.Localization;

var repo = args.Length > 0 ? Path.GetFullPath(args[0]) : FindRepo(Directory.GetCurrentDirectory());
var outDir = Path.Combine(repo, "src", "MissionPlanner.App", "Localization");
Directory.CreateDirectory(outDir);

// ---- 1. harvest ------------------------------------------------------------------------------

var tags = new HashSet<string>(
    LanguageCatalog.Languages.SelectMany(l => LanguageCatalog.Sources(l.Code)), StringComparer.OrdinalIgnoreCase);
var stringsResx = Path.Combine(repo, "ExtLibs", "Strings", "Strings.resx");

var english = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
var translated = new List<(string Tag, string EnglishPath, string Path)>();
foreach (var file in EnumerateResx(repo))
{
    var name = Path.GetFileNameWithoutExtension(file);
    var dot = name.LastIndexOf('.');
    if (dot > 0 && tags.Contains(name[(dot + 1)..]))
        translated.Add((name[(dot + 1)..], Path.Combine(Path.GetDirectoryName(file)!, name[..dot] + ".resx"), file));
    else
        english[file] = ResxReader.ReadStrings(File.ReadAllText(file));
}

Console.WriteLine($"{english.Count} English .resx files, {translated.Count} translated");

var jsonOptions = new JsonSerializerOptions
{
    WriteIndented = true,
    Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
};
var tables = new Dictionary<string, TranslationTable>(StringComparer.Ordinal);

foreach (var language in LanguageCatalog.Languages.Where(l => l.Code != LanguageCatalog.English))
{
    var harvest = new ResxHarvest();
    var sources = LanguageCatalog.Sources(language.Code);
    var files = 0;
    for (var tier = 0; tier < sources.Count; tier++)
    {
        foreach (var t in translated.Where(t => string.Equals(t.Tag, sources[tier], StringComparison.OrdinalIgnoreCase))
                     .OrderBy(t => t.Path, StringComparer.Ordinal))
        {
            if (!english.TryGetValue(t.EnglishPath, out var source))
                continue;
            var rank = tier * 2 + (string.Equals(t.EnglishPath, stringsResx, StringComparison.Ordinal) ? 0 : 1);
            if (harvest.Add(source, ResxReader.ReadStrings(File.ReadAllText(t.Path)), rank) > 0)
                files++;
        }
    }

    var strings = harvest.Build();
    var path = Path.Combine(outDir, language.Code + ".json");
    var overrides = ReadOverrides(path);

    var root = new JsonObject
    {
        ["culture"] = language.Code,
        ["name"] = language.NativeName,
        ["englishName"] = language.EnglishName,
        ["colon"] = harvest.Colon,
        ["about"] = $"\"strings\" is generated by src/tools/LocalizationHarvest from {files} of Mission Planner's .resx translation files; " +
                    "do not edit it. Put additions and corrections in \"overrides\" (English text: translation), which the tool keeps " +
                    "and which win over \"strings\".",
        ["overrides"] = overrides,
        ["strings"] = ToJson(strings),
    };
    File.WriteAllText(path, root.ToJsonString(jsonOptions) + "\n", new UTF8Encoding(false));

    using var stream = File.OpenRead(path);
    tables[language.Code] = TranslationTable.Load(stream, language.Code);
    Console.WriteLine($"{language.Code,-8} {strings.Count,5} strings from {files} files, colon '{harvest.Colon}'");
}

// ---- 2. the app's strings and coverage --------------------------------------------------------

var appStrings = new Dictionary<string, string>(StringComparer.Ordinal); // key → first form seen
var src = Path.Combine(repo, "src");
var translatedProperties = new HashSet<string>(StringComparer.Ordinal);
// the desktop app and the phone app (MissionPlanner.Mobile shares the tables)
foreach (var file in new[] { "MissionPlanner.App", "MissionPlanner.Mobile" }.SelectMany(d => EnumerateSources(Path.Combine(src, d), "*.axaml")))
{
    var xaml = File.ReadAllText(file);
    AddStrings(UiStringScanner.ScanXaml(xaml));
    translatedProperties.UnionWith(UiStringScanner.ScanXamlTranslatedBindings(xaml));
}

foreach (var dir in new[] { "MissionPlanner.App", "MissionPlanner.App.Core", "MissionPlanner.Mobile" })
{
    foreach (var file in EnumerateSources(Path.Combine(src, dir), "*.cs"))
    {
        // the localization code itself only has examples in its comments
        if (file.Contains($"{Path.DirectorySeparatorChar}Localization{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
            continue;
        var code = File.ReadAllText(file);
        AddStrings(UiStringScanner.ScanCSharp(code));
        AddStrings(UiStringScanner.ScanAssignments(code, translatedProperties));
    }
}

var missing = appStrings.ToDictionary(p => p.Key, _ => new List<string>(), StringComparer.Ordinal);
var report = new StringBuilder();
foreach (var language in LanguageCatalog.Languages.Where(l => l.Code != LanguageCatalog.English))
{
    var table = tables[language.Code];
    var done = 0;
    foreach (var (key, text) in appStrings)
    {
        if (table.TryTranslate(text, out _))
            done++;
        else
            missing[key].Add(language.Code);
    }

    var line = $"{language.Code,-8} {language.EnglishName,-22} {done,5} / {appStrings.Count} ({100.0 * done / Math.Max(1, appStrings.Count):F0}%)";
    report.AppendLine("#   " + line);
    Console.WriteLine(line);
}

var all = LanguageCatalog.Languages.Count - 1;
var lines = missing.Where(p => p.Value.Count > 0)
    .Select(p => (Text: appStrings[p.Key], Missing: p.Value))
    .OrderBy(p => p.Text, StringComparer.OrdinalIgnoreCase).ThenBy(p => p.Text, StringComparer.Ordinal)
    .Select(p => Escape(p.Text) + "\t" + (p.Missing.Count == all ? "all" : string.Join(" ", p.Missing)));

var header = $"""
    # English UI strings of the app that have no translation yet, and the languages missing them.
    # Generated by src/tools/LocalizationHarvest (re-run it after adding strings); {appStrings.Count} strings in all.
    # To translate one, add it to the "overrides" section of src/MissionPlanner.App/Localization/<culture>.json:
    #   "overrides": {"{"} "Install Firmware": "..." {"}"}
    # (keys are the English text without a trailing ':' or '...'; case does not matter).
    #
    # Translated, per language:
    {report.ToString().TrimEnd()}
    #
    # <English text> TAB <cultures without it, or "all">

    """;
File.WriteAllText(Path.Combine(outDir, "untranslated.txt"), header + string.Join("\n", lines) + "\n", new UTF8Encoding(false));
Console.WriteLine($"{appStrings.Count} app strings, {missing.Count(p => p.Value.Count > 0)} missing in at least one language");
return 0;

void AddStrings(IEnumerable<string> texts)
{
    foreach (var text in texts)
    {
        var parts = LocalizationText.Split(text);
        if (parts.Core.Length == 0 || !LocalizationText.HasLetters(parts.Core))
            continue;
        appStrings.TryAdd(parts.Core.ToLowerInvariant(), text.Trim());
    }
}

static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t");

static JsonObject ToJson(SortedDictionary<string, string> strings)
{
    var obj = new JsonObject();
    foreach (var (k, v) in strings.OrderBy(p => p.Key, StringComparer.OrdinalIgnoreCase).ThenBy(p => p.Key, StringComparer.Ordinal))
        obj[k] = v;
    return obj;
}

static JsonObject ReadOverrides(string path)
{
    if (!File.Exists(path))
        return new JsonObject();
    try
    {
        var node = JsonNode.Parse(File.ReadAllText(path), documentOptions: new JsonDocumentOptions
        {
            AllowTrailingCommas = true,
            CommentHandling = JsonCommentHandling.Skip,
        });
        return node?["overrides"] is JsonObject o ? (JsonObject)o.DeepClone() : new JsonObject();
    }
    catch (JsonException ex)
    {
        throw new InvalidOperationException($"{path} is not valid JSON; fix it before re-running ({ex.Message})");
    }
}

static IEnumerable<string> EnumerateResx(string repo)
{
    var skip = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { ".git", "bin", "obj", "packages", "node_modules", ".claude" };
    var stack = new Stack<string>();
    stack.Push(repo);
    while (stack.Count > 0)
    {
        var dir = stack.Pop();
        foreach (var sub in Directory.GetDirectories(dir).OrderBy(d => d, StringComparer.Ordinal))
        {
            var name = Path.GetFileName(sub);
            // the new app's own sources are not a translation source
            if (skip.Contains(name) || (dir == repo && name == "src"))
                continue;
            stack.Push(sub);
        }

        foreach (var file in Directory.GetFiles(dir, "*.resx").OrderBy(f => f, StringComparer.Ordinal))
            yield return file;
    }
}

static IEnumerable<string> EnumerateSources(string dir, string pattern) =>
    Directory.GetFiles(dir, pattern, SearchOption.AllDirectories)
        .Where(f => !f.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}", StringComparison.Ordinal)
                    && !f.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
        .OrderBy(f => f, StringComparer.Ordinal);

static string FindRepo(string start)
{
    for (var dir = new DirectoryInfo(start); dir != null; dir = dir.Parent)
    {
        if (File.Exists(Path.Combine(dir.FullName, "MissionPlanner.Next.sln")))
            return dir.FullName;
    }

    throw new InvalidOperationException("run inside the repository or pass its path");
}
